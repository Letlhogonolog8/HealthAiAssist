async function main() {
  console.log(`Genomics API smoke test against ${BASE}\n`);

  // --- transparency endpoints, no auth ---
  const panels = await call('GET', '/api/genomics/panels');
  check('GET /panels returns 200', panels.status === 200, `got ${panels.status}`);
  check(
    'melanoma panel is a real PGS Catalog score',
    panels.json?.polygenicPanels?.some(
      (p: any) => p.condition === 'melanoma' && p.provenance === 'pgs_catalog' && p.clinicalUseAllowed === true
    ),
    JSON.stringify(panels.json?.polygenicPanels)
  );
  check(
    'melanoma panel has a reference distribution',
    panels.json?.polygenicPanels?.some(
      (p: any) => p.condition === 'melanoma' && p.hasReferenceDistribution === true
    )
  );
  check(
    'actionable panel is real ClinVar data',
    panels.json?.actionablePanel?.synthetic === false &&
    panels.json?.actionablePanel?.clinicalUseAllowed === true,
    JSON.stringify(panels.json?.actionablePanel)
  );

  const transfer = await call('GET', '/api/genomics/transferability');
  check('GET /transferability returns 200', transfer.status === 200);
  const african = transfer.json?.groups?.find((g: any) => g.group === 'african');
  check('African group withholds percentile', african?.percentileReported === false);

  // --- register + login ---
  // Usernames are capped at 20 chars by the registration schema, so the
  // uniqueness suffix has to be short.
  const suffix = Date.now().toString(36).slice(-6);
  const username = `geno_${suffix}`;
  const reg = await call('POST', '/api/auth/register', {
    username,
    password: 'GenoProbe123',
    role: 'patient',
    fullName: 'Genomics Probe',
    email: `${username}@example.com`,
  });
  check('registration succeeds', reg.status === 200, JSON.stringify(reg.json));
  const patientId = reg.json?.id;
  if (!patientId) {
    console.error('\nCannot continue without a patient id.');
    process.exit(1);
  }

  const login = await call('POST', '/api/auth/login', { username, password: 'GenoProbe123' });
  check('login succeeds', login.status === 200, JSON.stringify(login.json));

  const me = await call('GET', '/api/auth/me');
  if (me.status !== 200) {
    console.error(
      '\nSession did not persist across requests, so the authenticated portion ' +
      'cannot run. This is a pre-existing session issue, not a genomics one.'
    );
    process.exit(failures.length ? 1 : 0);
  }

  // --- consent is required before upload ---
  const form = new FormData();
  form.append('patientId', String(patientId));
  form.append('selfReportedAncestry', 'European');
  form.append('genotypeFile', new Blob([GENOTYPE_FILE], { type: 'text/plain' }), 'genome.txt');

  // Self-access is permitted without an explicit grant, so upload should work.
  const upload = await call('POST', '/api/genomics/profile/upload', undefined, form);
  check('upload succeeds for self', upload.status === 200, JSON.stringify(upload.json));
  check('only panel-relevant variants stored', upload.json?.variantsStored === 24,
    `stored ${upload.json?.variantsStored}`);
  check('build detected', upload.json?.genomeBuild === 'GRCh37');

  // --- risk computation ---
  const risk = await call('POST', `/api/genomics/risk/${patientId}`, { condition: 'melanoma' });
  check('risk computation returns 200', risk.status === 200, JSON.stringify(risk.json).slice(0, 300));
  // Both panels are now sourced, so nothing synthetic remains to block use.
  check('no synthetic data remains in the result',
    risk.json?.containsSyntheticData === false && risk.json?.clinicalUseAllowed === true,
    `synthetic=${risk.json?.containsSyntheticData} allowed=${risk.json?.clinicalUseAllowed}`);
  check('clinician review always required', risk.json?.requiresClinicianReview === true);
  check('polygenic component came from the real panel',
    risk.json?.polygenic?.provenance === 'pgs_catalog',
    JSON.stringify(risk.json?.polygenic));
  check('full panel coverage achieved', risk.json?.polygenic?.coveragePct === 100,
    `coverage ${risk.json?.polygenic?.coveragePct}%`);
  check('percentile computed for European ancestry',
    typeof risk.json?.polygenic?.percentile === 'number',
    `withheld: ${risk.json?.polygenic?.percentileWithheldReason}`);
  check('deliberately high-risk profile scores in a high percentile',
    (risk.json?.polygenic?.percentile ?? 0) >= 90,
    `percentile ${risk.json?.polygenic?.percentile}`);
  check('ancestry block present', risk.json?.ancestry?.group === 'european');
  check('actionable finding surfaced', (risk.json?.actionableVariants?.findings?.length ?? 0) >= 1);
  check('band raised to high by pathogenic finding', risk.json?.band === 'high',
    `band was ${risk.json?.band}`);
  check('no synthetic caveat is emitted',
    !risk.json?.caveats?.some((c: string) => /SYNTHETIC/i.test(c)));
  check('un-assayed panel positions reported as unknown',
    (risk.json?.actionableVariants?.notAssayedCount ?? 0) > 1000,
    `notAssayed ${risk.json?.actionableVariants?.notAssayedCount}`);

  // --- audit trail ---
  const log = await call('GET', `/api/genomics/access-log/${patientId}`);
  check('access log readable by patient', log.status === 200);
  check('upload and compute_risk both logged',
    ['upload', 'compute_risk'].every((a: string) =>
      log.json?.entries?.some((e: any) => e.action === a)));

  // --- consent revocation is recorded ---
  const revoke = await call('POST', '/api/genomics/consent', {
    patientId, scope: 'research', granted: false,
  });
  check('consent revocation recorded', revoke.status === 200 &&
    revoke.json?.consents?.research?.granted === false);

  // --- deletion keeps the audit trail ---
  const del = await call('DELETE', `/api/genomics/profile/${patientId}`);
  check('genomic data deletable', del.status === 200, JSON.stringify(del.json));
  const logAfter = await call('GET', `/api/genomics/access-log/${patientId}`);
  check('access log survives deletion', (logAfter.json?.entries?.length ?? 0) > 0);

  console.log(`\n${passed} passed, ${failures.length} failed`);
  if (failures.length) {
    console.error('\nFAILURES:');
    for (const f of failures) console.error(`  - ${f}`);
    process.exit(1);
  }
}

main().catch((error) => {
  console.error('Smoke test crashed:', error);
  process.exit(1);
});
