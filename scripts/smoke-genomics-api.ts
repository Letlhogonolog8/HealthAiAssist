/**
 * End-to-end smoke test for the genomics API against a running server.
 *
 * Exercises the paths that unit tests cannot: consent enforcement across HTTP,
 * multipart upload, persistence, and the audit trail.
 *
 *   npm run dev            # in one terminal
 *   npx tsx scripts/smoke-genomics-api.ts [baseUrl]
 */
const BASE = (process.argv[2] || 'http://localhost:5000').trim().replace(/\/+$/, '');

// The WHATWG fetch spec maintains a blocked-port list, and Node's fetch enforces
// it. A server listening on one of these is unreachable from this script and the
// only symptom is "bad port", which does not point at the cause.
const BLOCKED_PORTS = new Set([
  1719, 1720, 1723, 2049, 3659, 4045, 5060, 5061, 6000, 6566, 6665, 6666, 6667,
  6668, 6669, 6697, 10080,
]);
const parsedPort = Number.parseInt(new URL(BASE).port, 10);
if (BLOCKED_PORTS.has(parsedPort)) {
  console.error(
    `Port ${parsedPort} is on the fetch blocked-port list and cannot be reached ` +
    'by this script. Start the server on a different port.'
  );
  process.exit(1);
}

let cookie = '';
let passed = 0;
const failures: string[] = [];

async function call(
  method: string,
  path: string,
  body?: any,
  form?: FormData
): Promise<{ status: number; json: any }> {
  const headers: Record<string, string> = {};
  if (cookie) headers.Cookie = cookie;
  if (body) headers['Content-Type'] = 'application/json';

  const res = await fetch(`${BASE}${path}`, {
    method,
    headers,
    body: form ? (form as any) : body ? JSON.stringify(body) : undefined,
  });

  const setCookie = res.headers.get('set-cookie');
  if (setCookie) cookie = setCookie.split(';')[0];

  let json: any = null;
  try {
    json = await res.json();
  } catch {
    /* non-JSON responses are reported via status alone */
  }
  return { status: res.status, json };
}

function check(name: string, condition: boolean, detail?: string): void {
  if (condition) {
    passed++;
    console.log(`  PASS  ${name}`);
  } else {
    failures.push(`${name}${detail ? ` — ${detail}` : ''}`);
    console.log(`  FAIL  ${name}${detail ? ` — ${detail}` : ''}`);
  }
}

// Real PGS000339 (melanoma) variants, genotyped so the effect allele is present
