function prsAt(percentile: number | null, provenance: 'pgs_catalog' | 'synthetic' = 'pgs_catalog') {
  return {
    panelId: 'TEST', condition: 'melanoma', provenance,
    rawScore: 1, matchedVariants: 5, panelSize: 5, coveragePct: 100,
    percentile, percentileWithheldReason: percentile === null ? 'withheld' : null,
    warnings: [],
  };
}

const FLAGGED: Parameters<typeof fuseRisk>[0]['imaging'] = {
  scanId: 1, flagged: true, confidence: 95, riskLevel: 'high',
};
const CLEAR: Parameters<typeof fuseRisk>[0]['imaging'] = {
  scanId: 2, flagged: false, confidence: 90, riskLevel: 'low',
};

test('a flagged high-risk scan sets the band high', () => {
  const result = fuseRisk({ condition: 'melanoma', imaging: FLAGGED });
  assert.equal(result.band, 'high');
});

test('a low polygenic score cannot lower a flagged lesion', () => {
  const result = fuseRisk({
    condition: 'melanoma',
    imaging: FLAGGED,
    prs: prsAt(5),
    transferability: getTransferability('European'),
  });
  assert.equal(result.band, 'high', 'a reassuring PRS must never talk down imaging');
});

test('a high polygenic score raises a clear scan to moderate', () => {
  const result = fuseRisk({
    condition: 'melanoma',
    imaging: CLEAR,
    prs: prsAt(95),
    transferability: getTransferability('European'),
  });
  assert.equal(result.band, 'moderate');
});

test('an untransferable polygenic score is excluded, not down-weighted', () => {
  const result = fuseRisk({
    condition: 'melanoma',
    imaging: CLEAR,
    prs: prsAt(99),
    transferability: getTransferability('African'),
  });
  assert.equal(result.band, 'low', 'a score that does not transfer must not move the band');
  const prsContribution = result.contributions.find((c) => c.source === 'polygenic_score');
  assert.equal(prsContribution?.effect, 'excluded');
});

test('a pathogenic finding raises the band to high on its own', () => {
  const result = fuseRisk({
    condition: 'melanoma',
    imaging: CLEAR,
    actionable: screenActionableVariants(new Map([['rsP1', 'AA'], ['rsP2', 'CC'], ['rsV1', 'AA']]), ACTIONABLE),
  });
  assert.equal(result.band, 'high');
});

test('no inputs yields indeterminate, explicitly not low', () => {
  const result = fuseRisk({ condition: 'melanoma' });
  assert.equal(result.band, 'indeterminate');
  assert.ok(result.caveats.some((c) => /not a low-risk result/i.test(c)));
  assert.ok(result.missingInputs.length >= 3);
});

test('synthetic input blocks clinical use and leads the caveats', () => {
  const result = fuseRisk({
    condition: 'melanoma',
    imaging: CLEAR,
    prs: prsAt(95, 'synthetic'),
    transferability: getTransferability('European'),
  });
  assert.equal(result.containsSyntheticData, true);
  assert.match(result.caveats[0], /SYNTHETIC/);
});

test('every fused result demands clinician review', () => {
  for (const input of [
    { condition: 'melanoma', imaging: FLAGGED },
    { condition: 'melanoma', imaging: CLEAR },
    { condition: 'melanoma' },
  ]) {
    assert.equal(fuseRisk(input).requiresClinicianReview, true);
  }
});

test('missing imaging is named in the output', () => {
  const result = fuseRisk({
    condition: 'melanoma',
    prs: prsAt(95),
    transferability: getTransferability('European'),
  });
  assert.ok(result.missingInputs.some((m) => /imaging/i.test(m)));
});

