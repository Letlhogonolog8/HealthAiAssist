const ACTIONABLE: ActionablePanel = {
  source: 'test',
  version: 'v1',
  synthetic: false,
  variants: [
    { rsid: 'rsP1', gene: 'BRCA1', riskAllele: 'A', classification: 'pathogenic', condition: 'HBOC', clinvarId: '1', inheritance: 'AD' },
    { rsid: 'rsP2', gene: 'BRCA2', riskAllele: 'T', classification: 'pathogenic', condition: 'HBOC', clinvarId: '2', inheritance: 'AD' },
    { rsid: 'rsV1', gene: 'BRCA2', riskAllele: 'G', classification: 'uncertain_significance', condition: 'HBOC', clinvarId: '3', inheritance: 'AD' },
  ],
};

test('actionable screening reports a pathogenic carrier', () => {
  const result = screenActionableVariants(new Map([['rsP1', 'AG'], ['rsP2', 'CC'], ['rsV1', 'AA']]), ACTIONABLE);
  assert.equal(result.findings.length, 1);
  assert.equal(result.findings[0].gene, 'BRCA1');
  assert.equal(result.findings[0].copies, 1);
});

test('variants of uncertain significance are not reported as findings', () => {
  const result = screenActionableVariants(new Map([['rsP1', 'GG'], ['rsP2', 'CC'], ['rsV1', 'GG']]), ACTIONABLE);
  assert.equal(result.findings.length, 0, 'VUS must not surface as a finding');
});

test('un-assayed positions are counted as unknown, not negative', () => {
  const result = screenActionableVariants(new Map([['rsP1', 'GG']]), ACTIONABLE);
  assert.equal(result.notAssayed.length, 2);
  assert.equal(result.assayedNegative, 1);
  assert.ok(result.caveats.some((c) => /not negative/i.test(c)));
});

test('no installed panel reports "not screened", never a clean result', () => {
  const result = screenActionableVariants(new Map([['rsP1', 'AA']]), null);
  assert.equal(result.screened, false);
  assert.equal(result.findings.length, 0);
  assert.ok(result.caveats.some((c) => /not a negative result/i.test(c)));
});

test('a clean screen still warns that coverage is partial', () => {
  const all = new Map([['rsP1', 'GG'], ['rsP2', 'CC'], ['rsV1', 'AA']]);
  const result = screenActionableVariants(all, ACTIONABLE);
  assert.equal(result.findings.length, 0);
  assert.ok(result.caveats.some((c) => /does NOT rule out/i.test(c)));
});

