/**
 * Tests for the genomics risk engine.
 *
 * Only the pure modules are exercised here — parsers, scoring, ancestry
 * calibration, actionable screening and fusion. They have no database
 * dependency, so this runs anywhere with `npm run test:genomics`.
 *
 * The assertions concentrate on the failure modes that would be invisible in
 * production: a missing genotype silently counted as zero risk alleles, a
 * percentile released for an ancestry it does not describe, a reassuring
 * polygenic score talking down a flagged lesion, synthetic data escaping into a
 * clinical field.
 */
import assert from 'node:assert/strict';

import { parseConsumerRawFile, parseVcf, parseGenotypeFile, GenotypeParseError } from '../server/genomics/parsers';
import { dosage, computePrs, parsePgsScoringFile, type ScoringPanel } from '../server/genomics/prs';
import { getTransferability, percentileInterval, resolveAncestryGroup } from '../server/genomics/ancestry';
import { screenActionableVariants, type ActionablePanel } from '../server/genomics/actionable-variants';
import { fuseRisk } from '../server/genomics/fusion';

let passed = 0;
const failures: string[] = [];

function test(name: string, fn: () => void): void {
  try {
    fn();
    passed++;
  } catch (error) {
    failures.push(`${name}\n    ${error instanceof Error ? error.message : String(error)}`);
  }
}

