test('unknown ancestry does not default to European', () => {
  const transfer = getTransferability(null);
  assert.equal(transfer.group, 'unknown');
  assert.equal(transfer.percentileReportable, false, 'must not report a percentile');
  assert.ok(transfer.factor < 1.0);
});

test('African ancestry withholds the percentile', () => {
  const transfer = getTransferability('African');
  assert.equal(transfer.group, 'african');
  assert.equal(transfer.percentileReportable, false);
  assert.ok(transfer.factor <= 0.3, 'should reflect substantially reduced accuracy');
});

test('European ancestry reports a percentile at full factor', () => {
  const transfer = getTransferability('European');
  assert.equal(transfer.percentileReportable, true);
  assert.equal(transfer.factor, 1.0);
});

test('ancestry aliases resolve free text', () => {
  assert.equal(resolveAncestryGroup('Black South African'), 'african');
  assert.equal(resolveAncestryGroup('Han Chinese'), 'east_asian');
  assert.equal(resolveAncestryGroup('  '), null);
  assert.equal(resolveAncestryGroup('Klingon'), null, 'unrecognised must not be guessed');
});

test('lower transferability produces a visibly wider interval', () => {
  const narrow = percentileInterval(50, 1.0);
  const wide = percentileInterval(50, 0.25);
  assert.ok(wide.widthPct > narrow.widthPct * 2, 'poor transfer must widen the band');
});

