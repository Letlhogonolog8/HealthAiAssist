test('dosage counts effect allele copies', () => {
  assert.equal(dosage('CT', 'T'), 1);
  assert.equal(dosage('TT', 'T'), 2);
  assert.equal(dosage('CC', 'T'), 0);
});

test('dosage returns null for a no-call rather than zero', () => {
  // Treating a missing genotype as 0 copies silently biases every score down.
  assert.equal(dosage('--', 'T'), null);
  assert.equal(dosage('', 'T'), null);
});

const PANEL: ScoringPanel = {
  id: 'TEST-PANEL',
  condition: 'melanoma',
  provenance: 'pgs_catalog',
  pgsId: 'PGS999999',
  genomeBuild: 'GRCh37',
  discoveryAncestry: 'European',
  citation: 'test',
  variants: [
    { rsid: 'rs1', effectAllele: 'T', otherAllele: 'C', weight: 0.5 },
    { rsid: 'rs2', effectAllele: 'G', otherAllele: 'A', weight: 0.25 },
    { rsid: 'rs3', effectAllele: 'A', otherAllele: 'G', weight: 1.0 },
    { rsid: 'rs4', effectAllele: 'C', otherAllele: 'T', weight: 0.1 },
    { rsid: 'rs5', effectAllele: 'T', otherAllele: 'A', weight: 0.2 },
  ],
};

test('prs sums weight x dosage over genotyped variants', () => {
  const genotypes = new Map([
    ['rs1', 'TT'],  // 2 x 0.5  = 1.0
    ['rs2', 'AG'],  // 1 x 0.25 = 0.25
    ['rs3', 'GG'],  // 0 x 1.0  = 0
    ['rs4', 'CC'],  // 2 x 0.1  = 0.2
    ['rs5', 'AT'],  // 1 x 0.2  = 0.2
  ]);
  const result = computePrs(PANEL, genotypes, { mean: 1.0, sd: 0.5 });
  assert.ok(Math.abs(result.rawScore - 1.65) < 1e-9, `expected 1.65, got ${result.rawScore}`);
  assert.equal(result.coveragePct, 100);
  assert.equal(result.matchedVariants, 5);
});

test('prs withholds a percentile below the coverage floor', () => {
  const genotypes = new Map([['rs1', 'TT'], ['rs2', 'AG']]); // 40% coverage
  const result = computePrs(PANEL, genotypes, { mean: 1.0, sd: 0.5 });
  assert.equal(result.coveragePct, 40);
  assert.equal(result.percentile, null);
  assert.match(result.percentileWithheldReason ?? '', /genotyped/i);
});

test('prs withholds a percentile when no reference distribution exists', () => {
  const genotypes = new Map(PANEL.variants.map((v) => [v.rsid, `${v.effectAllele}${v.effectAllele}`]));
  const result = computePrs(PANEL, genotypes, null);
  assert.equal(result.percentile, null);
  assert.match(result.percentileWithheldReason ?? '', /reference distribution/i);
});

test('prs excludes no-calls from coverage instead of scoring them as zero', () => {
  const withNoCall = new Map([
    ['rs1', 'TT'], ['rs2', 'AG'], ['rs3', '--'], ['rs4', 'CC'], ['rs5', 'AT'],
  ]);
  const result = computePrs(PANEL, withNoCall, { mean: 1.0, sd: 0.5 });
  assert.equal(result.matchedVariants, 4, 'no-call must not count as genotyped');
  assert.equal(result.coveragePct, 80);
});

test('prs refuses a percentile when genome builds disagree', () => {
  const genotypes = new Map(PANEL.variants.map((v) => [v.rsid, `${v.effectAllele}${v.effectAllele}`]));
  const result = computePrs(PANEL, genotypes, { mean: 1.0, sd: 0.5 }, 'GRCh38');
  assert.equal(result.percentile, null, 'GRCh37 panel vs GRCh38 genotypes must not score');
  assert.match(result.percentileWithheldReason ?? '', /build mismatch/i);
  assert.ok(result.warnings.some((w) => /build mismatch/i.test(w)));
});

test('prs scores normally when builds match', () => {
  const genotypes = new Map(PANEL.variants.map((v) => [v.rsid, `${v.effectAllele}${v.effectAllele}`]));
  const result = computePrs(PANEL, genotypes, { mean: 1.0, sd: 0.5 }, 'GRCh37');
  assert.notEqual(result.percentile, null);
});

test('prs warns when the genotype build is undeclared', () => {
  const genotypes = new Map(PANEL.variants.map((v) => [v.rsid, `${v.effectAllele}${v.effectAllele}`]));
  const result = computePrs(PANEL, genotypes, { mean: 1.0, sd: 0.5 }, null);
  assert.ok(result.warnings.some((w) => /did not declare a reference build/i.test(w)));
});

test('prs flags synthetic panels in its warnings', () => {
  const synthetic: ScoringPanel = { ...PANEL, provenance: 'synthetic' };
  const genotypes = new Map(PANEL.variants.map((v) => [v.rsid, `${v.effectAllele}${v.effectAllele}`]));
  const result = computePrs(synthetic, genotypes, { mean: 1, sd: 0.5 });
  assert.ok(result.warnings.some((w) => /synthetic/i.test(w)));
});

test('pgs catalog scoring file parses metadata and variants', () => {
  const file = [
    '#pgs_id=PGS000123',
    '#genome_build=GRCh37',
    'rsID\teffect_allele\tother_allele\teffect_weight',
    'rs100\tA\tG\t0.15',
    'rs200\tT\tC\t-0.08',
  ].join('\n');
  const panel = parsePgsScoringFile(file, 'melanoma');
  assert.equal(panel.pgsId, 'PGS000123');
  assert.equal(panel.genomeBuild, 'GRCh37');
  assert.equal(panel.provenance, 'pgs_catalog');
  assert.equal(panel.variants.length, 2);
  assert.equal(panel.variants[1].weight, -0.08);
});

