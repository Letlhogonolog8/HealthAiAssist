const CONSUMER_FILE = [
  '# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2024',
  '# build 37',
  '#rsid\tchromosome\tposition\tgenotype',
  'rs1805007\t16\t89986117\tCT',
  'rs12913832\t15\t28365618\tAG',
  'rs16891982\t5\t33951693\t--',
  'rs1393350\t11\t89011046\tGA',
].join('\n');

test('consumer parser reads genotypes and detects build', () => {
  const result = parseConsumerRawFile(CONSUMER_FILE);
  assert.equal(result.source, '23andme');
  assert.equal(result.genomeBuild, 'GRCh37');
  assert.equal(result.genotypes.length, 4);
});

test('consumer parser sorts alleles so GA and AG are equal', () => {
  const result = parseConsumerRawFile(CONSUMER_FILE);
  const rs1393350 = result.genotypes.find((g) => g.rsid === 'rs1393350');
  assert.equal(rs1393350?.genotype, 'AG', 'GA should normalise to AG');
});

test('consumer parser normalises no-calls to --', () => {
  const result = parseConsumerRawFile(CONSUMER_FILE);
  assert.equal(result.genotypes.find((g) => g.rsid === 'rs16891982')?.genotype, '--');
});

test('consumer parser warns when build is undeclared', () => {
  const noBuild = '#rsid\tchromosome\tposition\tgenotype\nrs1805007\t16\t89986117\tCT';
  const result = parseConsumerRawFile(noBuild);
  assert.equal(result.genomeBuild, null);
  assert.ok(result.warnings.some((w) => /build/i.test(w)), 'should warn about missing build');
});

test('consumer parser rejects a file with no genotype rows', () => {
  assert.throws(() => parseConsumerRawFile('# only a header\n'), GenotypeParseError);
});

test('consumer parser keeps the first call for a duplicated rsid', () => {
  const dup = [
    '# build 37',
    'rs1805007\t16\t89986117\tCT',
    'rs1805007\t16\t89986117\tTT',
  ].join('\n');
  const result = parseConsumerRawFile(dup);
  assert.equal(result.genotypes.length, 1);
  assert.equal(result.genotypes[0].genotype, 'CT');
  assert.equal(result.skipped, 1);
});

const VCF_FILE = [
  '##fileformat=VCFv4.2',
  '##reference=GRCh37',
  '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE1',
  '16\t89986117\trs1805007\tC\tT\t50\tPASS\t.\tGT\t0/1',
  '15\t28365618\trs12913832\tA\tG\t50\tPASS\t.\tGT\t1/1',
  '11\t89011046\trs1393350\tG\tA\t50\tPASS\t.\tGT\t./.',
].join('\n');

test('vcf parser maps GT fields to diploid calls', () => {
  const result = parseVcf(VCF_FILE);
  assert.equal(result.source, 'vcf');
  assert.equal(result.genomeBuild, 'GRCh37');
  const byRsid = new Map(result.genotypes.map((g) => [g.rsid, g.genotype]));
  assert.equal(byRsid.get('rs1805007'), 'CT', 'het 0/1 should be REF+ALT');
  assert.equal(byRsid.get('rs12913832'), 'GG', 'hom 1/1 should be ALT+ALT');
  assert.equal(byRsid.get('rs1393350'), '--', 'missing ./. should be a no-call');
});

test('vcf parser refuses multi-sample files rather than guessing a column', () => {
  const multi = VCF_FILE.replace('\tSAMPLE1', '\tSAMPLE1\tSAMPLE2');
  assert.throws(() => parseVcf(multi), /single-sample/i);
});

test('format dispatch picks the parser from content, not filename', () => {
  assert.equal(parseGenotypeFile(VCF_FILE).source, 'vcf');
  assert.equal(parseGenotypeFile(CONSUMER_FILE).source, '23andme');
});

